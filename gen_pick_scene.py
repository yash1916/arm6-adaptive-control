"""Generate arm6_pick.xml: the CAD arm + working gripper + cube + goal marker, from cad_props.json and the STL meshes.

Differences from arm6.xml (gen_mjcf.py):
  * fingers are SLIDE joints (one per finger) driven by force-limited position servos
  * finger collision boxes with high friction; a cube (free body) and the floor collide with them
  * arm links still have collisions OFF (we plan paths that keep them clear of the floor)
  * a green mocap disc marks the goal
  * fingers are placed at y = +/-32 mm (open gap 56 mm) instead of the CAD's +/-20 mm (32 mm) so a 30 mm cube fits
    with 13 mm clearance per side. This is a deliberate model change; the CAD itself is unchanged.
"""
import json
import numpy as np

meta = json.load(open("cad_props.json"))
O = {k: np.array(v) * 1e-3 for k, v in meta["part_origin_world_mm"].items()}
P = meta["parts"]; J = meta["joints_mm"]
LIMITS = dict(joint1=(-3.5, 3.5), joint2=(-2.0, 2.0), joint3=(-2.5, 2.5), joint4=(-3.14, 3.14), joint5=(-2.0, 2.0), joint6=(-3.14, 3.14))
TORQUE = dict(joint1=120, joint2=150, joint3=100, joint4=30, joint5=30, joint6=15)
DAMP = dict(joint1=1.0, joint2=1.0, joint3=0.8, joint4=0.3, joint5=0.2, joint6=0.1)
COLOR = dict(base="0.55 0.60 0.68 1", link1_turntable="0.24 0.29 0.36 1", link2_upper="0.29 0.33 0.40 1",
             link3_forearm="0.36 0.40 0.47 1", link4_forearm_roll="0.42 0.47 0.54 1", link5_wrist="0.48 0.53 0.60 1",
             link6_gripper="0.17 0.18 0.21 1", finger="0.88 0.48 0.12 1")
FINGER_Y = 0.032          # finger centre offset from the tool axis when open (m)
FINGER_STROKE = 0.03      # how far each finger can close (m)
CUBE_HALF = 0.015
FRIC = "1.5 0.01 0.001"


def f(v): return " ".join(f"{x:.8g}" for x in v)


def inertial(part):
    p = P[part]; I = np.array(p["inertia_com_kgm2"])
    return (f'<inertial pos="{f(p["com_m"])}" mass="{p["mass_kg"]:.8g}" '
            f'fullinertia="{I[0,0]:.8g} {I[1,1]:.8g} {I[2,2]:.8g} {I[0,1]:.8g} {I[0,2]:.8g} {I[1,2]:.8g}"/>')


def vis(part): return f'<geom type="mesh" mesh="{part}" rgba="{COLOR[part]}" contype="0" conaffinity="0"/>'


def body(name, part, parent_origin, jname, children=""):
    pos = O[name] - parent_origin
    jx = (f'<joint name="{jname}" type="hinge" axis="{f(J[jname]["axis"])}" range="{LIMITS[jname][0]} {LIMITS[jname][1]}" '
          f'damping="{DAMP[jname]}" armature="0.01"/>') if jname else ""
    return f'<body name="{name}" pos="{f(pos)}">{jx}{inertial(part)}{vis(part)}{children}</body>'


# ---- fingers: slide joints, collision box over the real finger length (x from 0 to 70 mm of the finger frame)
xf = (O["FingerL"] - O["Link6Gripper"])[0]            # finger base distance from the J6 origin along the tool axis
fingers = ""
for nm, sgn, jn in (("FingerL", +1, "fingerL"), ("FingerR", -1, "fingerR")):
    fingers += (f'<body name="{nm}" pos="{xf:.6f} {sgn * FINGER_Y:.6f} 0">'
                f'<joint name="{jn}" type="slide" axis="0 {-sgn} 0" range="0 {FINGER_STROKE}" damping="8" armature="0.002"/>'
                f'{inertial("finger")}{vis("finger")}'
                f'<geom name="{jn}_col" type="box" pos="0.035 0 0" size="0.035 0.004 0.012" rgba="0 0 0 0" '
                f'friction="{FRIC}" condim="4" contype="1" conaffinity="1" solref="0.005 1"/></body>')
tcp_x = xf + 0.070
tcp = f'<site name="tcp" pos="{tcp_x:.6f} 0 0" size="0.008" rgba="1 0.2 0.2 1"/>'
# an (almost) massless body at the tool tip; its mass is raised at run time to simulate an unknown payload
tcp += f'<body name="payload" pos="{tcp_x:.6f} 0 0"><inertial pos="0 0 0" mass="1e-6" diaginertia="1e-9 1e-9 1e-9"/></body>'

b6 = body("Link6Gripper", "link6_gripper", O["Link5Wrist"], "joint6", fingers + tcp)
b5 = body("Link5Wrist", "link5_wrist", O["Link4ForearmRoll"], "joint5", b6)
b4 = body("Link4ForearmRoll", "link4_forearm_roll", O["Link3Forearm"], "joint4", b5)
b3 = body("Link3Forearm", "link3_forearm", O["Link2Upper"], "joint3", b4)
b2 = body("Link2Upper", "link2_upper", O["Link1Turntable"], "joint2", b3)
b1 = body("Link1Turntable", "link1_turntable", O["Base"], "joint1", b2)

meshes = "\n    ".join(f'<mesh name="{p}" file="{p}.stl" scale="0.001 0.001 0.001"/>' for p in P)
acts = "\n    ".join(f'<motor name="m{i}" joint="joint{i}" ctrlrange="-{TORQUE[f"joint{i}"]} {TORQUE[f"joint{i}"]}" ctrllimited="true"/>' for i in range(1, 7))
acts += "\n    " + "\n    ".join(
    f'<position name="grip_{s}" joint="finger{s}" kp="1500" ctrlrange="0 {FINGER_STROKE}" forcerange="-60 60"/>' for s in ("L", "R"))

xml = f'''<mujoco model="arm6_pick">
  <!-- Generated by gen_pick_scene.py. Arm links: no collisions. Fingers, cube and floor: collide. -->
  <compiler angle="radian" meshdir="meshes/"/>
  <option gravity="0 0 -9.81" timestep="0.002" integrator="implicitfast" cone="elliptic" impratio="10"/>
  <visual><global offwidth="1280" offheight="720"/><headlight ambient="0.45 0.45 0.45" diffuse="0.6 0.6 0.6"/></visual>
  <asset>
    {meshes}
    <texture type="skybox" builtin="gradient" rgb1="0.82 0.87 0.93" rgb2="0.97 0.98 1" width="256" height="256"/>
    <texture name="grid" type="2d" builtin="checker" rgb1="0.90 0.92 0.95" rgb2="0.84 0.87 0.91" width="256" height="256"/>
    <material name="floor" texture="grid" texrepeat="8 8" reflectance="0"/>
  </asset>
  <worldbody>
    <light pos="0.6 -0.8 1.6" dir="-0.3 0.5 -1" diffuse="0.7 0.7 0.7" castshadow="false"/>
    <geom name="floor" type="plane" size="1.5 1.5 0.05" material="floor" friction="1 0.01 0.001" contype="1" conaffinity="1"/>
    <body name="Base" pos="0 0 0">{inertial("base")}{vis("base")}
      {b1}
    </body>
    <!-- ONE free body holds the object. Two geoms share it (box and cylinder); objects.py switches one off (contype 0; it must be
         compiled as colliding to be switchable), resizes them and sets the mass at run time, so the same compiled model serves every shape. -->
    <body name="cube" pos="0.4 0 {CUBE_HALF}">
      <freejoint name="cube_free"/>
      <inertial pos="0 0 0" mass="0.1" diaginertia="1.5e-5 1.5e-5 1.5e-5"/>
      <geom name="cube_geom" type="box" size="{CUBE_HALF} {CUBE_HALF} {CUBE_HALF}" rgba="0.85 0.15 0.15 1"
            friction="{FRIC}" condim="4" contype="1" conaffinity="1" solref="0.005 1"/>
      <geom name="cyl_geom" type="cylinder" size="{CUBE_HALF} {CUBE_HALF}" rgba="0.15 0.35 0.85 0"
            friction="{FRIC}" condim="4" contype="1" conaffinity="1" solref="0.005 1"/>
    </body>
    <body name="goal" mocap="true" pos="0.3 0.2 0.001">
      <geom type="cylinder" size="0.03 0.0005" rgba="0.1 0.8 0.3 0.6" contype="0" conaffinity="0"/>
    </body>
  </worldbody>
  <actuator>
    {acts}
  </actuator>
</mujoco>'''
open("arm6_pick.xml", "w").write(xml); print("wrote arm6_pick.xml")