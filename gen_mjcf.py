"""Generate arm6.xml from the CAD export (cad_props.json + STL meshes).
Every part was exported translated-only (no rotation) with its origin on its proximal joint axis, so each MuJoCo body
frame is axis-aligned with the world and body offsets are just differences of the part origins."""
import json, sys
import numpy as np

meta = json.load(open("cad_props.json"))
O = {k: np.array(v) * 1e-3 for k, v in meta["part_origin_world_mm"].items()}          # metres
P = meta["parts"]; J = meta["joints_mm"]
LIMITS = dict(joint1=(-3.14, 3.14), joint2=(-2.0, 2.0), joint3=(-2.5, 2.5), joint4=(-3.14, 3.14), joint5=(-2.0, 2.0), joint6=(-3.14, 3.14))
TORQUE = dict(joint1=120, joint2=150, joint3=100, joint4=30, joint5=30, joint6=15)    # N m motor limits
DAMP = dict(joint1=1.0, joint2=1.0, joint3=0.8, joint4=0.3, joint5=0.2, joint6=0.1)
COLOR = dict(base="0.55 0.60 0.68 1", link1_turntable="0.24 0.29 0.36 1", link2_upper="0.29 0.33 0.40 1",
             link3_forearm="0.36 0.40 0.47 1", link4_forearm_roll="0.42 0.47 0.54 1", link5_wrist="0.48 0.53 0.60 1",
             link6_gripper="0.17 0.18 0.21 1", finger="0.88 0.48 0.12 1")

def f(v): return " ".join(f"{x:.8g}" for x in v)

def inertial(part):
    p = P[part]; I = np.array(p["inertia_com_kgm2"])
    return (f'<inertial pos="{f(p["com_m"])}" mass="{p["mass_kg"]:.8g}" '
            f'fullinertia="{I[0,0]:.8g} {I[1,1]:.8g} {I[2,2]:.8g} {I[0,1]:.8g} {I[0,2]:.8g} {I[1,2]:.8g}"/>')

def geom(part): return f'<geom type="mesh" mesh="{part}" rgba="{COLOR[part]}" contype="0" conaffinity="0"/>'

def body(name, part, parent_origin, jname, children=""):
    pos = O[name] - parent_origin
    jx = ""
    if jname:
        jx = (f'<joint name="{jname}" type="hinge" axis="{f(J[jname]["axis"])}" range="{LIMITS[jname][0]} {LIMITS[jname][1]}" '
              f'damping="{DAMP[jname]}" armature="0.01"/>')
    return (f'<body name="{name}" pos="{f(pos)}">{jx}{inertial(part)}{geom(part)}{children}</body>')

fing = ""
tcp_local = np.array([8e-3 + 32e-3 + 1e-3 + 70e-3, 0, 0])
for nm, y in (("FingerL", None), ("FingerR", None)):
    pos = O[nm] - O["Link6Gripper"]
    fing += f'<body name="{nm}" pos="{f(pos)}">{inertial("finger")}{geom("finger")}</body>'
tcp = f'<site name="tcp" pos="{f(tcp_local)}" size="0.01" rgba="1 0.2 0.2 1"/>'
b6 = body("Link6Gripper", "link6_gripper", O["Link5Wrist"], "joint6", fing + tcp)
b5 = body("Link5Wrist", "link5_wrist", O["Link4ForearmRoll"], "joint5", b6)
b4 = body("Link4ForearmRoll", "link4_forearm_roll", O["Link3Forearm"], "joint4", b5)
b3 = body("Link3Forearm", "link3_forearm", O["Link2Upper"], "joint3", b4)
b2 = body("Link2Upper", "link2_upper", O["Link1Turntable"], "joint2", b3)
b1 = body("Link1Turntable", "link1_turntable", O["Base"], "joint1", b2)

meshes = "\n    ".join(f'<mesh name="{p}" file="{p}.stl" scale="0.001 0.001 0.001"/>' for p in P)
acts = "\n    ".join(f'<motor name="m{i}" joint="joint{i}" ctrlrange="-{TORQUE[f"joint{i}"]} {TORQUE[f"joint{i}"]}" ctrllimited="true"/>' for i in range(1, 7))
xml = f'''<mujoco model="arm6">
  <!-- Generated by gen_mjcf.py from the CAD export. Arm links have collisions OFF (contype=0): free-space control stage. -->
  <compiler angle="radian" meshdir="meshes/"/>
  <option gravity="0 0 -9.81" timestep="0.002" integrator="implicitfast"/>
  <visual><global offwidth="1280" offheight="720"/><headlight ambient="0.45 0.45 0.45" diffuse="0.6 0.6 0.6"/></visual>
  <asset>
    {meshes}
    <texture type="skybox" builtin="gradient" rgb1="0.82 0.87 0.93" rgb2="0.97 0.98 1" width="256" height="256"/>
    <texture name="grid" type="2d" builtin="checker" rgb1="0.90 0.92 0.95" rgb2="0.84 0.87 0.91" width="256" height="256"/>
    <material name="floor" texture="grid" texrepeat="8 8" reflectance="0"/>
  </asset>
  <worldbody>
    <light pos="0.6 -0.8 1.6" dir="-0.3 0.5 -1" diffuse="0.7 0.7 0.7" castshadow="false"/>
    <geom name="floor" type="plane" size="1.5 1.5 0.05" material="floor" contype="0" conaffinity="0"/>
    <body name="Base" pos="0 0 0">{inertial("base")}{geom("base")}
      {b1}
    </body>
  </worldbody>
  <actuator>
    {acts}
  </actuator>
  <keyframe><key name="home" qpos="0 0 0 0 0 0"/></keyframe>
</mujoco>'''
open("arm6.xml", "w").write(xml); print("wrote arm6.xml,", len(xml), "bytes")
